/**
 * Writes src/build-info.ts before every build and every dev server start.
 * The shell renders these values, so redeploying one app and seeing only that
 * app's buildId change is the visible evidence of an independent deploy.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (relativePath) => JSON.parse(readFileSync(join(appRoot, relativePath), 'utf8'));

function gitShortSha() {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: appRoot,
      stdio: ['ignore', 'pipe', 'ignore'],
      encoding: 'utf8',
    }).trim();
  } catch {
    // No commits yet, or git is not on PATH. The timestamp below still makes
    // every build distinguishable, so this is not worth failing the build over.
    return 'nogit';
  }
}

const pkg = readJson('package.json');
const buildInfo = {
  app: pkg.name,
  version: pkg.version,
  buildId: `${gitShortSha()}-${Date.now().toString(36)}`,
  builtAt: new Date().toISOString(),
  angularVersion: readJson('node_modules/@angular/core/package.json').version,
};

writeFileSync(
  join(appRoot, 'src/build-info.ts'),
  `// Generated by scripts/write-build-info.mjs on every build. Do not edit by hand.
import type { BuildInfo } from '@mfe-demo/platform';

export const BUILD_INFO: BuildInfo = ${JSON.stringify(buildInfo, null, 2)};
`,
);

console.log(`build-info: ${buildInfo.app}@${buildInfo.version} ${buildInfo.buildId}`);
